"""Turn pipeline/sources/*.json into SQL that registers organisations and sources in D1.

    python pipeline/scripts/sources_sql.py pipeline/sources/national-north.json > sources.sql
    npx wrangler d1 execute myavedan-staging --env staging --remote --file sources.sql   (from apps/api)

Upserts, so it can be re-run after the list changes. Only approved sources are registered.
"""

from __future__ import annotations

import json
import sys
from urllib.parse import urlparse

STATE_NAMES = {
    "uttar-pradesh": "Uttar Pradesh",
    "uttarakhand": "Uttarakhand",
    "himachal-pradesh": "Himachal Pradesh",
    "punjab": "Punjab",
    "haryana": "Haryana",
    "delhi": "Delhi",
    "chandigarh": "Chandigarh",
    "jammu-kashmir": "Jammu and Kashmir",
    "ladakh": "Ladakh",
    "rajasthan": "Rajasthan",
}
UTS = {"delhi", "chandigarh", "jammu-kashmir", "ladakh"}

# Extra official hosts some organisations publish notices on.
EXTRA_HOSTS = {
    "sbi": ["sbi.co.in"],
    "rrb-apply": ["rrbapply.gov.in"],
}


def q(value: str | None) -> str:
    return "NULL" if value is None else "'" + value.replace("'", "''") + "'"


def host_of(url: str) -> str:
    return (urlparse(url).hostname or "").removeprefix("www.")


def main(path: str) -> None:
    data = json.load(open(path, encoding="utf-8"))
    out = ["-- Generated by pipeline/scripts/sources_sql.py. Do not edit by hand."]
    for s in data["sources"]:
        if not s.get("approved_by_owner"):
            continue
        region = s["region"]
        jurisdiction = "central" if region == "national" else ("ut" if region in UTS else "state")
        state = None if region == "national" else STATE_NAMES.get(region, region)
        hosts = sorted({host_of(s["url"]), *EXTRA_HOSTS.get(s["id"], [])})
        org_id, src_id = f"org_{s['id']}", f"src_{s['id']}"
        tier = 1 if region == "national" else 2
        out.append(
            "INSERT INTO organization (id, name, jurisdiction, state, domains_json) VALUES "
            f"({q(org_id)}, {q(s['organization'])}, {q(jurisdiction)}, {q(state)}, {q(json.dumps(hosts))}) "
            "ON CONFLICT(id) DO UPDATE SET name = excluded.name, jurisdiction = excluded.jurisdiction, "
            "state = excluded.state, domains_json = excluded.domains_json;"
        )
        reason = s.get("note") or f"Official recruitment website of {s['organization']}"
        out.append(
            "INSERT INTO source (id, organization_id, url, kind, reason, cadence_minutes, tier, active) VALUES "
            f"({q(src_id)}, {q(org_id)}, {q(s['url'])}, 'html_list', {q(reason)}, 180, {tier}, 1) "
            "ON CONFLICT(id) DO UPDATE SET url = excluded.url, reason = excluded.reason, tier = excluded.tier, active = 1;"
        )
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
